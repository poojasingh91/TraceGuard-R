"""Streamlit dashboard for evidence-grounded synthetic incident reconstruction."""
import ast
import pandas as pd
import plotly.express as px
import streamlit as st
from normalize import load_events
from correlate import correlate

st.set_page_config(page_title="TraceGuard-R", page_icon="🛡️", layout="wide")
st.title("🛡️ TraceGuard-R")
st.caption("Trustworthy cyber incident reconstruction · synthetic demonstration data only")

try:
    events = load_events()
    alerts = correlate(events)
except (FileNotFoundError, ValueError) as exc:
    st.error(str(exc))
    st.stop()

c1, c2, c3, c4 = st.columns(4)
c1.metric("Events", f"{len(events):,}")
c2.metric("Candidate alerts", f"{len(alerts):,}")
c3.metric("High severity", int((alerts["severity"] == "high").sum()) if not alerts.empty else 0)
c4.metric("Log sources", int(events["source"].nunique()))

st.info("Alerts are investigative leads, not proof of an attack. 'Observed facts' describe records; 'Inference' describes a possible interpretation.")

st.subheader("Search events")
search = st.text_input("Search user, IP, hostname, event type, or event ID")
filtered = events.copy()
if search:
    mask = filtered.astype(str).apply(lambda col: col.str.contains(search, case=False, na=False)).any(axis=1)
    filtered = filtered[mask]
source_options = ["All"] + sorted(filtered["source"].unique().tolist())
source = st.selectbox("Source", source_options)
if source != "All":
    filtered = filtered[filtered["source"] == source]
st.dataframe(filtered.sort_values("timestamp", ascending=False), use_container_width=True, hide_index=True)

st.subheader("Candidate incident timeline")
if alerts.empty:
    st.success("No alerts generated by the current rules.")
else:
    severity = st.multiselect("Severity", ["high", "medium", "low"], default=["high", "medium"])
    user_options = sorted(alerts["user"].dropna().astype(str).unique().tolist())
    users = st.multiselect("User", user_options, default=user_options)
    shown = alerts[alerts["severity"].isin(severity) & alerts["user"].astype(str).isin(users)]
    timeline = shown.copy()
    timeline["start_time"] = pd.to_datetime(timeline["start_time"], utc=True)
    timeline["end_time"] = pd.to_datetime(timeline["end_time"], utc=True)
    if not timeline.empty:
        fig = px.scatter(timeline, x="start_time", y="user", color="severity",
                         hover_name="title", hover_data=["alert_id", "rule", "destination_host"],
                         title="Alert start times")
        st.plotly_chart(fig, use_container_width=True)
    st.dataframe(shown[["alert_id","start_time","end_time","severity","user","source_ip","destination_host","title"]],
                 use_container_width=True, hide_index=True)
    selected = st.selectbox("Inspect an alert", shown["alert_id"].tolist() if not shown.empty else [])
    if selected:
        alert = alerts[alerts["alert_id"] == selected].iloc[0]
        st.markdown(f"### {alert['title']}")
        st.write(f"**Severity:** {alert['severity']} · **Rule:** `{alert['rule']}`")
        st.write("**Observed facts**")
        st.write(alert["observed_facts"])
        st.write("**Possible interpretation (inference)**")
        st.write(alert["inference"])
        evidence_ids = alert["evidence_ids"]
        if isinstance(evidence_ids, str):
            try:
                evidence_ids = ast.literal_eval(evidence_ids)
            except (ValueError, SyntaxError):
                evidence_ids = [evidence_ids]
        st.write("**Original evidence records**")
        st.dataframe(events[events["event_id"].isin(evidence_ids)].sort_values("timestamp"),
                     use_container_width=True, hide_index=True)

st.caption("Next research milestone: test known scenarios, then introduce controlled missing records and timestamp offsets.")
